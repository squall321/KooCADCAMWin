// Number of involute sample points per flank.
constexpr int kFlankSamples = 24;

// Build a 2D polyline approximating one tooth-gap (gullet) cross-section,
// centred on +X axis (i.e. the gullet's CENTERLINE is angle 0 around +Z).
// Returns a closed wire ready to be made into a face and prism.
//
// Geometry of one gullet:
//   inner arc  : root circle    r_root
//   outer arc  : tip  circle    r_tip
//   left flank : involute from base circle out to tip (mirrored to -y side)
//   right flank: involute from base circle out to tip (on +y side)
//
// Both flanks shifted angularly so the GAP (gullet) opens toward +X.
TopoDS_Shape buildToothGapPrism(double moduleM, int z, double pressureAngleRad,
                                double faceWidth, double overhang)
{
    const double rPitch = moduleM * static_cast<double>(z) / 2.0;
    const double rBase  = rPitch * std::cos(pressureAngleRad);
    const double rTip   = rPitch + moduleM;
    const double rRoot  = std::max(rBase * 0.95, rPitch - 1.25 * moduleM);
    const double toothAngle = 2.0 * M_PI / static_cast<double>(z);

    // Find t_max where involute reaches r_tip:
    //   r(t) = r_base · sqrt(1 + t²)  →  t_max = sqrt((r_tip/r_base)² − 1)
    const double tMax = std::sqrt(std::max(0.0,
        (rTip / rBase) * (rTip / rBase) - 1.0));

    // Tooth thickness at pitch radius (chord) = π·m / 2.
    // Angular tooth thickness at pitch = π·m / (2·r_pitch) = π / z.
    // Half-angular-tooth-thickness at base circle (using involute function):
    //   inv(α) = tan(α) − α
    //   half_tooth_at_base = π/(2·z) + inv(α)
    const double invAlpha = std::tan(pressureAngleRad) - pressureAngleRad;
    const double halfToothAtBase = M_PI / (2.0 * static_cast<double>(z)) + invAlpha;

    // The TOOTH is centred at angle = +halfTooth on +Y side and -halfTooth on -Y side
    // relative to the gullet centerline.  We build a SINGLE gullet centred at
    // angle = 0 (around +X), so the tooth FLANK on the +Y side is the LEFT flank
    // of the +Y-neighbour tooth.  In involute math, that flank is generated by
    // the involute starting at angle = halfToothAtBase on the BASE circle.

    // Right flank polyline (on +Y side of gullet) — generated by involute at
    // base-circle angle = +halfToothAtBase, swept by t to r_tip.
    std::vector<gp_Pnt> rightFlank;
    rightFlank.reserve(kFlankSamples);
    for (int k = 0; k < kFlankSamples; ++k) {
        const double t = tMax * static_cast<double>(k) / static_cast<double>(kFlankSamples - 1);
        // Standard involute centred on +X:
        const double xi = rBase * (std::cos(t) + t * std::sin(t));
        const double yi = rBase * (std::sin(t) - t * std::cos(t));
        // Rotate by +halfToothAtBase so flank lands on +Y side of gullet centre.
        const double c = std::cos(halfToothAtBase);
        const double s = std::sin(halfToothAtBase);
        const double xr =  xi * c - yi * s;
        const double yr =  xi * s + yi * c;
        rightFlank.emplace_back(xr, yr, -overhang);
    }

    // Left flank — mirror of right flank about X axis.
    std::vector<gp_Pnt> leftFlank;
    leftFlank.reserve(kFlankSamples);
    for (int k = 0; k < kFlankSamples; ++k) {
        const gp_Pnt& p = rightFlank[k];
        leftFlank.emplace_back(p.X(), -p.Y(), -overhang);
    }

    // Bottom of gullet: arc of root circle from leftFlank[0] back to
    // rightFlank[0].  Approximate as a 3-segment polyline through angle 0.
    // leftFlank[0] is at angle = -halfToothAtBase on base circle (radius
    // rBase).  We extend INWARD to root radius along the same radial.
    // Build bottom land points: from rightFlank[0] (at +halfToothAtBase, rBase)
    // → out to (+halfToothAtBase, rRoot) → through (0, rRoot) → (-halfToothAtBase, rRoot)
    // → (leftFlank[0]).
    const double rBaseRight_x = rBase * std::cos(halfToothAtBase);
    const double rBaseRight_y = rBase * std::sin(halfToothAtBase);
    const double rRootRight_x = rRoot * std::cos(halfToothAtBase);
    const double rRootRight_y = rRoot * std::sin(halfToothAtBase);
    const double rRootCenter_x = rRoot;
    const double rRootCenter_y = 0.0;
    const double rRootLeft_x  = rRoot * std::cos(-halfToothAtBase);
    const double rRootLeft_y  = rRoot * std::sin(-halfToothAtBase);

    // OUTER closing edge: from rightFlank.last to leftFlank.last along tip
    // circle.  These two points are at angles +halfToothAtTip and -halfToothAtTip
    // — we just use a straight line (chord) over the tooth tip.  But the tip
    // is on the TOOTH side, not the gullet side; the gullet's OUTER side
    // actually goes from rightFlank.last → OUT past the tip to a "ceiling"
    // beyond rTip, then back down to leftFlank.last.  We use a ceiling at
    // r = rTip + overhang/r ≈ rTip + 1 mm to ensure the cut goes ALL the
    // way through the blank.
    const double rCeil = rTip + 2.0;
    const gp_Pnt rightLast = rightFlank[kFlankSamples - 1];
    const gp_Pnt leftLast  = leftFlank[kFlankSamples - 1];
    const double angRightLast = std::atan2(rightLast.Y(), rightLast.X());
    const double angLeftLast  = std::atan2(leftLast .Y(), leftLast .X());
    const gp_Pnt rightCeil(rCeil * std::cos(angRightLast),
                           rCeil * std::sin(angRightLast),
                           -overhang);
    const gp_Pnt leftCeil(rCeil * std::cos(angLeftLast),
                          rCeil * std::sin(angLeftLast),
                          -overhang);
    const gp_Pnt topCeil(rCeil, 0.0, -overhang);

    // Build the closed wire (CCW when looking down +Z, from outside the
    // workpiece).  Order:
    //   bottom-root-right → up rightFlank → out to rightCeil → over topCeil
    //   → leftCeil → down leftFlank (reversed) → root-left → root-center
    //   → root-right (back to start)
    BRepBuilderAPI_MakeWire wire;

    // 1. root: leftRoot → centerRoot → rightRoot
    wire.Add(BRepBuilderAPI_MakeEdge(
        gp_Pnt(rRootLeft_x,  rRootLeft_y,  -overhang),
        gp_Pnt(rRootCenter_x, rRootCenter_y, -overhang)).Edge());
    wire.Add(BRepBuilderAPI_MakeEdge(
        gp_Pnt(rRootCenter_x, rRootCenter_y, -overhang),
        gp_Pnt(rRootRight_x,  rRootRight_y, -overhang)).Edge());

    // 2. step out from rootRight to baseRight (start of involute right flank)
    wire.Add(BRepBuilderAPI_MakeEdge(
        gp_Pnt(rRootRight_x, rRootRight_y, -overhang),
        gp_Pnt(rBaseRight_x, rBaseRight_y, -overhang)).Edge());

    // 3. right flank (involute) from baseRight up to rightLast
    //    rightFlank[0] should be ≈ (rBaseRight_x, rBaseRight_y).
    for (int k = 0; k < kFlankSamples - 1; ++k) {
        wire.Add(BRepBuilderAPI_MakeEdge(rightFlank[k], rightFlank[k + 1]).Edge());
    }

    // 4. out to ceiling on right side
    wire.Add(BRepBuilderAPI_MakeEdge(rightLast, rightCeil).Edge());

    // 5. over the top: rightCeil → topCeil → leftCeil
    wire.Add(BRepBuilderAPI_MakeEdge(rightCeil, topCeil).Edge());
    wire.Add(BRepBuilderAPI_MakeEdge(topCeil,   leftCeil).Edge());

    // 6. down into leftLast
    wire.Add(BRepBuilderAPI_MakeEdge(leftCeil, leftLast).Edge());

    // 7. left flank reversed (from leftLast back down to leftFlank[0])
    for (int k = kFlankSamples - 1; k > 0; --k) {
        wire.Add(BRepBuilderAPI_MakeEdge(leftFlank[k], leftFlank[k - 1]).Edge());
    }

    // 8. step in from leftBase to leftRoot, closing the wire.
    const double rBaseLeft_x = rBase * std::cos(-halfToothAtBase);
    const double rBaseLeft_y = rBase * std::sin(-halfToothAtBase);
    wire.Add(BRepBuilderAPI_MakeEdge(
        gp_Pnt(rBaseLeft_x, rBaseLeft_y, -overhang),
        gp_Pnt(rRootLeft_x, rRootLeft_y, -overhang)).Edge());

    if (!wire.IsDone())
        throw Standard_Failure("spur_gear_involute: gullet wire build failed");

    BRepBuilderAPI_MakeFace face(wire.Wire(), true);
    if (!face.IsDone())
        throw Standard_Failure("spur_gear_involute: gullet face build failed");

    BRepPrimAPI_MakePrism prism(face.Face(),
        gp_Vec(0.0, 0.0, faceWidth + 2.0 * overhang));
    prism.Build();
    if (!prism.IsDone())
        throw Standard_Failure("spur_gear_involute: gullet prism build failed");

    (void)toothAngle;  // used downstream for replication
    return prism.Shape();
}

