// ── Validation ───────────────────────────────────────────────────────────

DFMReport validate(const Workpiece& wp, const Input& in)
{
    DFMReport r;
    if (in.module_mm <= 0.3 || in.module_mm > 50.0) {
        r.add("DFM-GEAR-MOD", "error",
              "spur_gear_involute: module_mm " +
              std::to_string(in.module_mm) + " out of (0.3, 50] mm");
    }
    if (in.teeth_count < 8 || in.teeth_count > 200) {
        r.add("DFM-GEAR-CT", "error",
              "spur_gear_involute: teeth_count " +
              std::to_string(in.teeth_count) + " out of [8, 200]");
    }
    if (in.face_width_mm <= 0.0) {
        r.add("DFM-GEAR-FW", "error",
              "spur_gear_involute: face_width_mm must be > 0");
    }
    if (in.pressure_angle_deg < 14.5 || in.pressure_angle_deg > 30.0) {
        r.add("DFM-GEAR-PA", "error",
              "spur_gear_involute: pressure_angle " +
              std::to_string(in.pressure_angle_deg) + " out of [14.5, 30] deg");
    }
    if (in.module_mm > 0.0 && in.teeth_count > 0) {
        const double rTip = in.module_mm * (in.teeth_count / 2.0 + 1.0);
        const double blankR = in.blank_outer_dia_mm > 0.0
            ? in.blank_outer_dia_mm / 2.0
            : rTip;
        if (blankR + 1e-6 < rTip) {
            r.add("DFM-GEAR-OD", "error",
                  "spur_gear_involute: blank_outer_dia " +
                  std::to_string(in.blank_outer_dia_mm) +
                  " smaller than required 2·r_tip " + std::to_string(2.0 * rTip));
        }
    }
    (void)wp;
    return r;
}

// ── Synthesis ────────────────────────────────────────────────────────────

SkillOutput apply(const Workpiece& wp, const Input& in)
{
    DFMReport dfm = validate(wp, in);
    if (!dfm.passed) {
        std::string msg = "spur_gear_involute DFM failed:";
        for (const auto& f : dfm.findings) msg += "\n  - " + f.code + ": " + f.message;
        throw SkillError(msg);
    }

    const double m       = in.module_mm;
    const int    z       = in.teeth_count;
    const double rPitch  = m * z / 2.0;
    const double rTip    = rPitch + m;
    const double rRoot   = rPitch - 1.25 * m;
    const double Z       = in.face_width_mm;
    const double alpha   = in.pressure_angle_deg * M_PI / 180.0;
    const double kOver   = 0.05;

    // Seed gullet at angle 0 (along +X).
    const TopoDS_Shape seedGullet =
        buildToothGapPrism(m, z, alpha, Z, kOver);

    // Replicate z times by rotation around +Z.
    const gp_Ax1 zAxis(gp_Pnt(0, 0, 0), gp::DZ());
    const double dTheta = 2.0 * M_PI / static_cast<double>(z);

    std::vector<TopoDS_Shape> cutters;
    cutters.reserve(static_cast<size_t>(z));
    for (int i = 0; i < z; ++i) {
        if (i == 0) {
            cutters.push_back(seedGullet);
            continue;
        }
        gp_Trsf rot;
        rot.SetRotation(zAxis, static_cast<double>(i) * dTheta);
        BRepBuilderAPI_Transform xf(seedGullet, rot, true);
        if (!xf.IsDone())
            throw SkillError("spur_gear_involute: cutter rotation failed");
        cutters.push_back(xf.Shape());
    }

    const TopoDS_Shape newShape = pr::cutMany(wp.shape(), cutters);

    // Volume removed (approx): z gullets, each ≈ (r_tip² − r_root²)·(toothAngle/2)·Z·0.5
    const double gulletVol =
        0.5 * (rTip * rTip - rRoot * rRoot) * (dTheta * 0.5) * Z;
    const double volRemoved = z * gulletVol;

    json params = {
        { "module_mm",          m },
        { "teeth_count",        z },
        { "face_width_mm",      Z },
        { "pressure_angle_deg", in.pressure_angle_deg },
        { "blank_outer_dia_mm", in.blank_outer_dia_mm > 0.0
                                  ? in.blank_outer_dia_mm : 2.0 * rTip },
    };
    json pattern = {
        { "kind",                  kSkillId },
        { "is_gear",               true },
        { "is_compound",           true },
        { "subfeature_count",      z },
        { "module_mm",             m },
        { "teeth_count",           z },
        { "pressure_angle_deg",    in.pressure_angle_deg },
        { "pitch_dia_mm",          2.0 * rPitch },
        { "tip_dia_mm",            2.0 * rTip },
        { "root_dia_mm",           2.0 * rRoot },
        { "face_width_mm",         Z },
        { "derived_volume_removed", volRemoved },
        { "standard",              "ISO 53" },
        { "profile",               "involute_sampled" },
    };

    ToolingMeta tooling;
    tooling.tool_type         = "gear_hob";
    tooling.tool_dia_mm       = m * 5.0;
    tooling.tool_length_mm    = Z * 2.0 + 10.0;
    tooling.tool_material     = "hss";
    tooling.flute_count       = 12;
    tooling.cutting_speed_sfm = 100.0;
    tooling.feed_per_tooth_mm = 0.04;
    tooling.stock_removed_mm3 = volRemoved;
    tooling.est_cycle_time_s  = std::max(30.0, z * 1.5 + 20.0);

    FeatureSignature sig{ kSkillId, params, pattern, tooling };

    auto wpNew = std::make_shared<Workpiece>(newShape, wp.material());
    wpNew->addFeature(sig);

    spdlog::debug("skill::spur_gear_involute applied: m={} z={} faces {}→{}",
                  m, z, wp.faceCount(), wpNew->faceCount());

    return SkillOutput{ wpNew, sig };
}

// ── Recognition ──────────────────────────────────────────────────────────
//
// Geometric: count Z-axis cylindrical faces + planar flanks clustered by
// angular sector around the gear axis.  Cluster count ≈ 2·z (each tooth
// contributes 2 flanks).  Fallback: metadata replay.

std::vector<RecognizedFeature> recognize(const Workpiece& wp)
{
    std::vector<RecognizedFeature> out;

    // ── Primary: geometric
    double xMin, yMin, zMin, xMax, yMax, zMax;
    wp.boundingBox(xMin, yMin, zMin, xMax, yMax, zMax);
    const double xMid = 0.5 * (xMin + xMax);
    const double yMid = 0.5 * (yMin + yMax);

    std::vector<double> flankAngles;
    int zCylCount = 0;
    for (int i = 0; i < wp.faceCount(); ++i) {
        if (wp.isFaceCylinder(i)) {
            BRepAdaptor_Surface s(wp.face(i));
            const gp_Cylinder cy = s.Cylinder();
            const gp_Dir d = cy.Axis().Direction();
            if (std::abs(std::abs(d.Z()) - 1.0) < 1e-2) ++zCylCount;
        } else if (wp.isFacePlanar(i)) {
            try {
                gp_Dir n = wp.faceNormal(i);
                if (std::abs(n.Z()) >= 0.3) continue;
                const gp_Pnt c = wp.faceCenter(i);
                const double dx = c.X() - xMid;
                const double dy = c.Y() - yMid;
                if (std::hypot(dx, dy) < 1.0) continue;
                flankAngles.push_back(std::atan2(dy, dx));
            } catch (...) {}
        }
    }

    if (flankAngles.size() >= 16) {
        std::sort(flankAngles.begin(), flankAngles.end());
        int clusterCount = 0;
        const double tol = 5.0 * M_PI / 180.0;
        for (size_t k = 0; k < flankAngles.size(); ++k) {
            if (k == 0 || std::abs(flankAngles[k] - flankAngles[k - 1]) > tol)
                ++clusterCount;
        }
        const int zEst = std::max(8, clusterCount / 2);
        if (zEst >= 8 && zEst <= 200) {
            const double od = std::max({ xMax - xMin, yMax - yMin });
            const double moduleEst = od / (static_cast<double>(zEst) + 2.0);
            const double thickness = zMax - zMin;
            json recovered = {
                { "module_mm",          moduleEst },
                { "teeth_count",        zEst },
                { "face_width_mm",      thickness },
                { "pressure_angle_deg", 20.0 },
                { "blank_outer_dia_mm", od },
            };
            json matched = {
                { "source",                "geometric_primary" },
                { "z_cyl_face_count",      zCylCount },
                { "flank_face_count",      static_cast<int>(flankAngles.size()) },
                { "angular_cluster_count", clusterCount },
                { "estimated_teeth_count", zEst },
            };
            out.push_back(RecognizedFeature{
                kSkillId, recovered, 0.7, matched
            });
        }
    }

    // ── Fallback: metadata replay
    for (const auto& f : wp.features()) {
        if (f.skill_id != kSkillId) continue;
        out.push_back(RecognizedFeature{
            kSkillId, f.params, 1.0,
            { { "source",       "feature_history_replay" },
              { "teeth_count",  f.pattern.value("teeth_count", 0) },
              { "module_mm",    f.pattern.value("module_mm",   0.0) } }
        });
    }
    return out;
}

